@pytest.mark.parametrize("case_id,carpark,lot,arrival,departure,holidays,expected,covers",
                         CASES, ids=[c[0] for c in CASES])
def test_fee_calculator_blackbox(case_id, carpark, lot, arrival, departure, holidays, expected, covers):
    calc = FeeCalculator(RulesRepo(), holidays=holidays)
    assert calc.calculate_fee_for(carpark, lot, arrival, departure) == money(expected)
