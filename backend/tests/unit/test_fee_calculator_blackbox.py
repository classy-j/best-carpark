"""Lab 4 §3.2.1: black-box tests of the FeeCalculator control class (UC-03, FR3.1-FR3.3).

Equivalence classes (EC) and boundary values (BV) are derived from the REQUIREMENTS, i.e.
HDB's published short-term parking charges (see app/collectors/seed_rates.py), not from the
code. Rate rules are generated by the real seed (spec_for), so each test uses the same rules
a real HDB carpark gets. Expected values were worked out by hand before running.

Input variables and classes:
  V1 rate data        EC1 carpark has rate rules            EC2 no rate rules
  V2 parking period   EC3 period <= 0                       EC4 0 < period <= grace (15 min, EPS)
                      EC5 grace < period, below day cap     EC6 period reaches day cap ($12)
  V3 charging mode    EC7 electronic, per minute            EC8 coupon, per started 30 min
  V4 time of day      EC9 day 07:00-22:30                   EC10 night 22:30-07:00 with night scheme
                      EC11 night at a carpark without the night parking scheme
  V5 day type         EC12 Mon-Fri  EC13 Saturday  EC14 Sunday  EC15 public holiday
  V6 location         EC16 outside Central Area             EC17 Central Area
  V7 free parking     EC18 Sun/PH free-parking scheme       EC19 no free-parking scheme
  V8 lot type         EC20 car  EC21 motorcycle  EC22 heavy vehicle
"""
from datetime import date, datetime
from decimal import Decimal

import pytest

from app.collectors.seed_rates import spec_for
from app.db.models import LotType
from app.db.records import SGT, RateRuleInfo
from app.services.fee_calculator import FeeCalculator


def hdb_record(ref="TST", system="ELECTRONIC PARKING", night="YES", free="NO", short_term="WHOLE DAY"):
    return {"car_park_no": ref, "type_of_parking_system": system, "night_parking": night,
            "free_parking": free, "short_term_parking": short_term}


# Carparks used by the tests (rules generated exactly as for real HDB carparks)
CARPARKS = {
    "EPS": hdb_record(),                                          # non-central, electronic, night scheme
    "COUPON_NO_NIGHT": hdb_record(system="COUPON PARKING", night="NO"),
    "CENTRAL": hdb_record(ref="ACB"),                             # ACB is in HDB's Central Area list
    "FREE_SUN": hdb_record(free="SUN & PH FR 7AM-10.30PM"),
    "NO_RATES": None,                                             # EC2: no rate scheme
}


class RulesRepo:
    """Stands in for CarparkRepository: rules for a carpark id + lot type."""
    def get_rate_rules(self, carpark_id, lot_type):
        record = CARPARKS[carpark_id]
        if record is None:
            return []
        spec = spec_for(record)
        lot = lot_type if isinstance(lot_type, LotType) else LotType(lot_type)
        return [RateRuleInfo(rule_id=i, rate_scheme_id=1, lot_type=r.lot_type, day_type=r.day_type,
                             start_time=r.start, end_time=r.end, charge_mode=r.mode, rate_sgd=r.rate,
                             interval_min=r.interval, per_minute=r.per_minute, first_interval_min=None,
                             first_rate_sgd=None, cap_sgd=r.cap, cap_scope=r.cap_scope, grace_min=r.grace,
                             priority=r.priority)
                for i, r in enumerate(spec.rules, start=1) if r.lot_type == lot]


HOLIDAY = date(2026, 10, 19)     # a Monday, declared a public holiday in the PH cases only


def t(day, hh, mm=0):            # 19 Oct 2026 = Monday, 24 = Saturday, 25 = Sunday
    return datetime(2026, 10, day, hh, mm, tzinfo=SGT)


def money(v):
    return None if v is None else Decimal(v)


